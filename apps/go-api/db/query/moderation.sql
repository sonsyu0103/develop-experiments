-- 【削除と記録は必ず同じトランザクションで行う】
-- 別トランザクションにすると、片方だけ成功した状態が作れる。
--   記録だけ成功 → 消えていないのに「消した」記録が残る
--   削除だけ成功 → 誰が消したか分からない (ADR 0010 の理由でログでは代替できない)
-- どちらも監査記録としては破綻している。
