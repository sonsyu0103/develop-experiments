-- =============================================================================
-- 000009: 通報キューを実際に処理できる形にする
-- =============================================================================
-- 000008 で作った reports を**使い始める段になって 2 つ足りないと分かった**。
-- どちらも ADR 0011 決定 4 の DDL をそのまま写したことに由来する。
--
-- **000008 は書き換えない。** 既に develop に入っており、
-- 適用済みの環境がありうる。マイグレーションは追記のみ。
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. コメントの通報にスレッド ID を持たせる
-- -----------------------------------------------------------------------------
-- **決定 4 の DDL には無かった。** target_id が BIGINT なので、
-- コメントを指す通報には ID しか入らない。
--
-- ところが comments は thread_id による HASH パーティションで、
-- 主キーが (thread_id, id) になる。**コメント ID だけでは
-- 8 パーティションすべてを走査しないと本文にも辿り着けない。**
--
-- キューは「通報された投稿を見て、消すかどうか判断する」ための画面なので、
-- 対象を引けないキューは用を成さない。削除 API
-- (POST /moderation/actions) も threadId を要求する。
--
-- 【moderation_actions と解決が違う理由】
-- あちらは target_id が TEXT なので "1:10" と複合キーを詰められた。
-- こちらは BIGINT で、決定 4 が「型が混ざらないので揃えて TEXT にはしない」
-- と決めている。**列を足すほうが、その決定と噛み合う。**
ALTER TABLE reports ADD COLUMN target_thread_id BIGINT;

-- スレッドの通報では NULL、コメントの通報では必須。
-- 「どちらの通報か」と「スレッド ID を持つか」がずれた行を作れないようにする。
ALTER TABLE reports ADD CONSTRAINT reports_thread_id_matches_target CHECK (
    (target_type = 'comment' AND target_thread_id IS NOT NULL)
    OR
    (target_type = 'thread' AND target_thread_id IS NULL)
);

-- -----------------------------------------------------------------------------
-- 2. キューの索引を created_at から id へ張り替える
-- -----------------------------------------------------------------------------
-- **created_at は一意ではない。**
--
-- 通報キューはキーセットページネーションで読む (OFFSET を使わないのは
-- README のとおり)。ところがキーセットの境界に一意でない列を使うと、
-- **同じ時刻の行が複数あるページ境界で取りこぼしと重複が起きる。**
-- 通報は「荒らしへの対応」という性質上、短時間に集中して届く ——
-- now() の解像度で並ぶ行が実際に生まれる。
--
-- id は IDENTITY なので一意かつ単調増加で、created_at の既定は now()。
-- **順序は実質同じで、一意性だけが得られる。**
--
-- 述語は変えない (status = 'open' のみ)。解決済みの通報は行として残るので
-- テーブルは単調増加するが、キューが読むのは open だけで、
-- そちらは処理が追いついていれば常に小さい。
DROP INDEX reports_open_idx;

CREATE INDEX reports_open_idx ON reports (id) WHERE status = 'open';
