-- =============================================================================
-- 000010: スレッドのタイトルにトライグラム索引を張る (Phase 11 / ADR 0012)
-- =============================================================================
-- title の中間一致 (LIKE '%語%') は B-Tree では索引が効かない。
-- B-Tree が効くのは前方一致だけで、中間一致は毎回全表走査になる。
--
-- pg_trgm は文字列を 3 文字のトライグラムに分解して GIN 索引に載せるため、
-- 中間一致でも索引が使える。**contrib なので RDS でも使える** ——
-- 日本語の精度なら pgroonga のほうが上だが、RDS でサポートされておらず
-- 「ローカルでだけ動く」設計になる (ADR 0012 の選択肢 C)。
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 0. 拡張があることを先に確かめる
-- -----------------------------------------------------------------------------
-- **拡張そのものはここでは作らない。** CREATE EXTENSION は superuser 権限の
-- 運用作業なので、db/init/00-extensions.sql に置いてある (ADR 0012 の決定)。
--
-- ところが db/init は**コンテナの初回起動時にしか走らない**。
-- Phase 11 より前に作ったボリュームには pg_trgm が入っておらず、
-- 下の CREATE INDEX が「type gin_trgm_ops does not exist」で落ちる。
-- エラーだけ見ても何をすればいいのか分からないので、ここで撃ち分ける。
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_trgm') THEN
        RAISE EXCEPTION
            '拡張 pg_trgm がありません。db/init は初回起動時にしか実行されないため、'
            'Phase 11 より前に作ったボリュームには入っていません。'
            'make clean && make up でデータベースを作り直してください';
    END IF;
END
$$;

-- -----------------------------------------------------------------------------
-- 1. 索引
-- -----------------------------------------------------------------------------
-- 部分索引にする理由は threads_alive_id_desc_idx と同じ。
-- 削除済みのスレッドは検索結果に出さないので、索引に載せる必要がない。
--
-- 【CONCURRENTLY を使っていない】
-- golang-migrate は 1 マイグレーションをトランザクションで包むため、
-- CREATE INDEX CONCURRENTLY は実行できない (トランザクション内では動かない)。
-- 既存行のあるテーブルに索引を張ると、その間 threads への書き込みが止まる。
-- 開発環境の行数では一瞬だが、**本番規模で流すなら
-- このマイグレーションだけ手で CONCURRENTLY に置き換えること。**
--
-- 【GIN の更新コストは問題にならない】
-- GIN は B-Tree より更新が重いが、**タイトルは作成時にしか書かれない**。
-- タイトルの編集機能を入れると、この前提は崩れる (ADR 0012 の罠)。
CREATE INDEX threads_title_trgm_idx
    ON threads USING gin (title gin_trgm_ops)
    WHERE deleted_at IS NULL;
