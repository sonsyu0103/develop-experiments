-- -----------------------------------------------------------------------------
-- threads: スレッド本体
-- -----------------------------------------------------------------------------
-- id に serial ではなく IDENTITY を使う理由:
--   serial は「integer + DEFAULT nextval + 所有シーケンス」の糖衣構文でしかなく、
--   列の型としては単なる integer。SQL 標準の GENERATED ... AS IDENTITY のほうが
--   意図が明確で、ALTER TABLE 時のシーケンス取り残しも起きない。
CREATE TABLE threads (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- 論理削除。物理削除しないのは、コメントの参照整合性を保ったまま
    -- 「スレだけ消す」運用を可能にするため。
    deleted_at TIMESTAMPTZ,

    CONSTRAINT threads_title_length CHECK (char_length(title) BETWEEN 1 AND 200)
);

-- 部分インデックス (partial index)。
-- 一覧取得は常に「生存スレッドを新しい順に N 件」なので、
-- deleted_at IS NULL の行だけを索引に載せればインデックスサイズを抑えられる。
-- MySQL には部分インデックスが存在しないため、同じことをするには
-- 「生存フラグ列 + 複合インデックス」で代用する必要がある。
CREATE INDEX threads_alive_id_desc_idx
    ON threads (id DESC)
    WHERE deleted_at IS NULL;


-- -----------------------------------------------------------------------------
-- comments: コメント (thread_id による HASH パーティション)
-- -----------------------------------------------------------------------------
-- パーティションテーブルでは IDENTITY 列が使えるのは PostgreSQL 17 以降。
-- 対応バージョンを広く取るため、明示シーケンス + DEFAULT nextval で採番する。
CREATE SEQUENCE comments_id_seq AS BIGINT;

CREATE TABLE comments (
    id          BIGINT      NOT NULL DEFAULT nextval('comments_id_seq'),
    thread_id   BIGINT      NOT NULL,
    author_name TEXT        NOT NULL DEFAULT '名無しさん',
    body        TEXT        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at  TIMESTAMPTZ,

    -- パーティションテーブルの一意制約は、必ずパーティションキーを含む必要がある。
    -- これは PostgreSQL が「一意性をパーティション横断で保証しない」ため。
    -- 列順を (thread_id, id) にしているのは、主キー索引をそのまま
    -- 「あるスレッドのコメントを id 順に読む」アクセスに使い回すため。
    CONSTRAINT comments_pkey PRIMARY KEY (thread_id, id),

    -- MySQL はパーティションテーブルに外部キーを一切張れない。
    -- PostgreSQL は張れる (PG11+)。これが RDBMS 選定の実質的な決め手のひとつ。
    CONSTRAINT comments_thread_id_fkey FOREIGN KEY (thread_id)
        REFERENCES threads (id) ON DELETE CASCADE,

    CONSTRAINT comments_body_length   CHECK (char_length(body) BETWEEN 1 AND 2000),
    CONSTRAINT comments_author_length CHECK (char_length(author_name) BETWEEN 1 AND 50)
) PARTITION BY HASH (thread_id);

ALTER SEQUENCE comments_id_seq OWNED BY comments.id;

-- HASH パーティションを 8 分割で静的に作る。
--
-- 【重要】現在のデータ量ではパーティショニングは性能上まったく不要である。
-- 数万行程度ならインデックスだけで十分で、むしろプランニングコストの分だけ不利。
-- ここで導入しているのは「どの規模から効き始めるか」をベンチマーク (Phase 4) で
-- 実測するためであり、必要だから入れているのではない。
--
-- 【実測後の追記 (Phase 4 / make partition-probe)】
-- **2,000 万行まで測って、効き始める規模には届かなかった。**
-- 除外は正しく効いている (実行計画に Subplans Removed: 7 が出る) のに、
-- 1 スレッドのコメント一覧はプリペアドステートメントで
-- 分割あり / なしとも 0.042 ms で差が出ない ——
-- **8 分割しても B-tree の段数が変わらない**ため。
-- 32 分割はすべての項目で 8 分割より悪かった。
--
-- 「どの規模から効き始めるか」という問いは、いずれ効き始めることを
-- 前提にしていたが、この形のクエリでは効き始める規模が現実的な範囲に無い。
-- **この 8 分割を性能で正当化してはいけない。** 残す価値があるとすれば
-- 保守の側 (区画ごとの VACUUM、索引の作り直し、古い区画の切り離し) になる。
-- 数字は docs/adr/0009-scaling-strategy.md の「実測」節。
--
-- RANGE(created_at) ではなく HASH(thread_id) を選んだ理由:
--   - 参照系がほぼ全て「特定スレッドのコメント」なので、
--     thread_id で切れば partition pruning がほぼ常に効く
--   - RANGE(created_at) は将来分のパーティションを作り続ける運用が必要になる
--     (pg_partman や cron)。静的に閉じる HASH のほうが保守コストが低い
CREATE TABLE comments_p0 PARTITION OF comments FOR VALUES WITH (MODULUS 8, REMAINDER 0);
CREATE TABLE comments_p1 PARTITION OF comments FOR VALUES WITH (MODULUS 8, REMAINDER 1);
CREATE TABLE comments_p2 PARTITION OF comments FOR VALUES WITH (MODULUS 8, REMAINDER 2);
CREATE TABLE comments_p3 PARTITION OF comments FOR VALUES WITH (MODULUS 8, REMAINDER 3);
CREATE TABLE comments_p4 PARTITION OF comments FOR VALUES WITH (MODULUS 8, REMAINDER 4);
CREATE TABLE comments_p5 PARTITION OF comments FOR VALUES WITH (MODULUS 8, REMAINDER 5);
CREATE TABLE comments_p6 PARTITION OF comments FOR VALUES WITH (MODULUS 8, REMAINDER 6);
CREATE TABLE comments_p7 PARTITION OF comments FOR VALUES WITH (MODULUS 8, REMAINDER 7);

-- 生存コメントのみの部分インデックス。
-- 主キー (thread_id, id) と重複して見えるが、こちらは deleted_at IS NULL に
-- 絞られている分だけ小さく、一覧取得のワーキングセットが小さくなる。
CREATE INDEX comments_alive_thread_id_desc_idx
    ON comments (thread_id, id DESC)
    WHERE deleted_at IS NULL;
