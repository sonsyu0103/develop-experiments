-- =============================================================================
-- 000014: 誰も書かない threads.updated_at を消す
-- =============================================================================
-- **000001 で作ってから、この列を更新する文が 1 本も無い** (DB レビュー)。
-- db/query を探しても threads.updated_at に触れる文は無く、API にも出ていない。
-- 値は INSERT 時の DEFAULT now() のまま、常に created_at と同じになっている。
--
-- 「スレッドの最終更新 (= 最後に投稿された時刻)」として使う案は
-- ADR 0019 の B で検討され、採られなかった。投稿のたびに threads の行を
-- 更新するのはホットロウ競合で、閲覧数を主トランザクションに混ぜないと
-- 決めた ADR 0006 と正面から矛盾するためである。
--
-- 名前が意味を約束しているのに値が伴わない列は、読む人を誤らせる。
-- 使う日が来たら、そのとき更新の経路と一緒に足す。
--
-- 【ロック】
-- DROP COLUMN はカタログの変更だけで、テーブルを書き換えない。
-- ACCESS EXCLUSIVE ロックは取るが、保持するのは一瞬で済む。
-- =============================================================================

ALTER TABLE threads DROP COLUMN updated_at;
