-- role は 3 段階。**投稿を消せる権限と、権限を配れる権限を分ける**ため
-- (ADR 0011 決定 1)。moderator を増やしても、権限を配れる人間は増えない。
--
-- 別テーブル (user_roles) にしないのは、1 ユーザーが持つロールが 1 つで、
-- 多対多にする理由がないため。組み合わせの制御が要るときに切り出す。
--
-- DEFAULT 'user' により、既存の行はすべて一般利用者になる。
-- NOT NULL にできるのはこの既定値があるため。
ALTER TABLE users ADD COLUMN role TEXT NOT NULL DEFAULT 'user';

-- 値を CHECK で縛る。列挙型 (CREATE TYPE) を使わないのは、
-- 値の追加に ALTER TYPE が要り、トランザクション内での扱いが
-- バージョンによって変わるため。TEXT + CHECK なら移行が読みやすい。
--
-- **アプリ側にも同じ 3 値を置く。** 片方だけ増やすと、
-- 保存できない値をアプリが作るか、アプリが知らない値が DB に入る。
ALTER TABLE users ADD CONSTRAINT users_role_valid
    CHECK (role IN ('user', 'moderator', 'admin'));

-- 管理者一覧のための部分索引 (ADR 0016 の区分 C)。
--
-- 【なぜ部分索引か】
-- 該当するのは数十行で、圧倒的多数は 'user' になる。
-- 全行を対象にすると索引の大半が「一般利用者」で埋まり、
-- 読まれないページを維持し続けることになる。
--
-- 述語を role <> 'user' にしているのは、moderator と admin を
-- 1 本で拾うため。役割ごとに分けると索引が 2 本になり、
-- 「モデレーター以上を一覧する」問い合わせで両方を読むことになる。
--
-- **この索引だけ 000003 に置く理由**は ADR 0016 に書いてある。
-- 000002 に書くと、まだ存在しない role 列を参照して落ちる。
CREATE INDEX users_privileged_idx ON users (id) WHERE role <> 'user';
