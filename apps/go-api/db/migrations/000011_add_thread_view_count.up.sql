-- =============================================================================
-- 000011: スレッドに閲覧数を持たせる (Phase 7 / ADR 0006)
-- =============================================================================
-- 「人気のスレッド一覧」の指標を閲覧数と定めた。
--
-- **この列の更新は、コメント投稿・スレッド作成のトランザクションに
-- 絶対に混ぜないこと。** 別の接続・別のトランザクション・READ COMMITTED で行う
-- (ADR 0006 の決定)。性能上の最適化ではなく、Phase 2 の測定を成立させる前提になる。
--
-- 混ぜると threads に対する rw-conflict が大量に生まれ、
-- **閲覧というまったく無関係な操作が、コメント投稿の直列化失敗率を押し上げる。**
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. 列
-- -----------------------------------------------------------------------------
-- NOT NULL DEFAULT 0。PostgreSQL 11 以降、定数の DEFAULT を持つ列の追加は
-- 全行の書き換えを伴わない (カタログだけを更新する) ので、既存行が多くても速い。
--
-- **BIGINT にする。** 掲示板の閲覧回数は投稿数より桁が多く、
-- INT の上限 (約 21 億) は「人気スレッド 1 つ」で到達しうる範囲に入る。
-- 後から広げるほうが高い。
ALTER TABLE threads
    ADD COLUMN view_count BIGINT NOT NULL DEFAULT 0;

-- CHECK を置くのは、フラッシュの実装が負の増分を書かないことを DB 側でも
-- 保証するため。バッファの集計が壊れたとき、**気づかないまま順位が入れ替わる**
-- のがいちばん困る (表示用の指標なので、誰も検算しない)。
ALTER TABLE threads
    ADD CONSTRAINT threads_view_count_non_negative CHECK (view_count >= 0);

-- -----------------------------------------------------------------------------
-- 2. 人気順の索引
-- -----------------------------------------------------------------------------
-- 人気順のカーソルは (view_count, id) の複合キーになる (ADR 0006)。
--
--   WHERE deleted_at IS NULL AND (view_count, id) < ($1, $2)
--   ORDER BY view_count DESC, id DESC
--
-- 行値比較は AND/OR に展開した条件と違い、この索引をそのまま辿れる。
--
-- **id を第 2 キーに入れるのが必須。** 閲覧数が同値のスレッドは必ず存在し、
-- 同値の並びが不定だとページ境界で行が重複・欠落する。
--
-- 部分索引にする理由は threads_alive_id_desc_idx と同じ。
--
-- 【この索引は HOT update を殺す】
-- PostgreSQL の HOT (Heap Only Tuple) update は、更新対象の列が
-- どの索引にも含まれていないときにだけ効く。view_count を索引に載せた時点で、
-- 1 回の更新がヒープと索引の両方を書くようになる (ADR 0006 の問題 3)。
--
-- **それでも載せる。** 「全スレッドを閲覧数順に並べて上位 20 件」を
-- 索引なしで解くと全表走査になり、人気一覧そのものが成立しない。
-- 代わりに更新回数のほうを減らす —— それがメモリ上のバッファリング (決定 D)。
-- 更新は「閲覧のたび」ではなく「フラッシュ間隔ごと」になる。
--
-- HOT update 率とデッドタプルの増加速度は Phase 4 の測定項目になる。
CREATE INDEX threads_alive_popular_idx
    ON threads (view_count DESC, id DESC)
    WHERE deleted_at IS NULL;
