-- =============================================================================
-- 000008: 通報 (reports) とモデレーション記録 (moderation_actions)
-- =============================================================================
-- 判断の記録は docs/adr/0011-moderation.md 決定 3・4、
-- 索引とマイグレーションの分割は docs/adr/0016-schema-and-indexes.md。
--
-- **2 つのテーブルを 1 本にまとめている。** ADR 0016 の「マイグレーションの
-- 分割」の表が 000008 に両方を割り当てているため、そのまま従う。
-- 使い始める時期は違う (moderation_actions は削除 API、reports は通報 API) が、
-- スキーマは 1 度に置く —— どちらもモデレーションの土台であり、
-- 分けると「reports だけある状態」で通報キューの索引設計をやり直すことになる。
--
-- 【この 2 つを thread / comment に寄せない】
-- 通報とモデレーション記録は thread / comment / image のいずれにも属さない。
-- どれかに寄せると他の 2 つへの参照が必要になり、モジュール境界が壊れる
-- (ADR 0011 のモジュール構成)。アプリ側も internal/moderation として独立させる。
-- =============================================================================

-- -----------------------------------------------------------------------------
-- moderation_actions: 誰が・何を・なぜ消したか (ADR 0011 決定 3)
-- -----------------------------------------------------------------------------
-- **ログではなく DB に書く。** ADR 0010 が「ログは at-most-once であり
-- 欠落しうる。課金・監査に使う数値をログの件数から数えない」と決めている。
-- モデレーション記録はまさに監査であり、「誰が消したか分からない」は許容できない。
-- ログにも出すが、正はこのテーブルになる。
CREATE TABLE moderation_actions (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 操作した人。**NULL を許さない。** 「誰が」が欠けた監査記録は
    -- 記録が無いのと変わらない。匿名のモデレーターは存在しない
    -- (この操作にはログインとロールが要る)。
    --
    -- 外部キーは users(id) を指す。ADR 0005 が「アカウント削除は行を消さず
    -- 匿名化する」と決めているため、この参照が宙に浮くことはない。
    actor_id    BIGINT      NOT NULL REFERENCES users(id),

    action      TEXT        NOT NULL,
    target_type TEXT        NOT NULL,

    -- **TEXT にしている。** threads / comments が BIGINT、images が UUID で
    -- 型が混在するため (ADR 0011 の引き受けるコスト)。
    -- ADR 0003 の未決 #11 が「用途ごとに使い分ける (統一しない)」決定に
    -- なったので、この混在は解消されない。
    --
    -- **外部キーを張れない。** 型が違うものを 1 列に詰めている以上、
    -- 参照整合性は保証できない —— 削除済みの対象を指す行が残りうる。
    -- 監査記録としてはそれで正しい (対象が消えても「消した事実」は残す)。
    --
    -- 【コメントだけ複合キーになる】
    --   thread   "7"
    --   comment  "1:10"  ← {thread_id}:{comment_id}
    --   image    "018f2c00-0000-7000-8000-000000000001"
    --   user     "42"
    --
    -- comments は thread_id による HASH パーティションで主キーが
    -- (thread_id, id) なので、**コメント ID だけでは下の
    -- moderation_actions_target_idx から辿れない** (8 パーティション全走査)。
    -- TEXT にしたのは型が混在するためだが、複合キーを表せるのが
    -- ここで効いている (ADR 0011 の実装して分かったこと 2)。
    target_id   TEXT        NOT NULL,

    -- 理由。**NULL 可。** 緊急の削除で理由を書かせないために任意にする。
    -- 記録の価値はここに集まるので、UI 側では入力を促す。
    reason      TEXT,

    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- 最後の砦 (comments_body_length などと同じ位置づけ)。
    -- アプリ側の型 (internal/moderation/domain/model) と**必ず同じ値**にすること。
    --
    -- change_role がここにあるのは、ロール変更も監査対象だから
    -- (ADR 0011 決定 1「変更は監査記録に残す」)。
    -- 書くのは専用のエンドポイントで、削除 API とは入力の形が違う。
    CONSTRAINT moderation_action_valid CHECK (
        action IN ('delete_thread', 'delete_comment', 'delete_image', 'change_role')
    ),
    CONSTRAINT moderation_target_type_valid CHECK (
        target_type IN ('thread', 'comment', 'image', 'user')
    ),
    -- 理由の上限。無いと監査テーブルに任意長の文字列を書き込ませられる。
    -- OpenAPI 側の maxLength と同じ値にすること。
    CONSTRAINT moderation_reason_length CHECK (reason IS NULL OR char_length(reason) <= 500),
    -- target_id の上限。UUID (36) と BIGINT (最大 20) が入れば足りる。
    CONSTRAINT moderation_target_id_length CHECK (char_length(target_id) BETWEEN 1 AND 64)
);

-- 「このモデレーターが何をしたか」を新しい順に引く。
-- 誤操作の調査は必ず「誰の操作か」から入るため、actor_id が先頭になる。
CREATE INDEX moderation_actions_actor_idx ON moderation_actions (actor_id, created_at DESC);

-- 「この投稿に何が起きたか」を引く。復活の判断に使う。
-- target_type を先頭に置くのは、target_id だけでは
-- thread の 10 と comment の 10 が同じ値になるため。
CREATE INDEX moderation_actions_target_idx ON moderation_actions (target_type, target_id);

-- -----------------------------------------------------------------------------
-- reports: 通報 (ADR 0011 決定 4)
-- -----------------------------------------------------------------------------
-- **通報はログイン必須。** 投稿は匿名を許すが (ADR 0005 決定 2)、
-- 通報は匿名にしない。非対称だが、投稿は表現、通報は他人への申し立てであり、
-- 後者には責任の所在が要る。匿名で受けると、通報そのものが荒らしの手段になる
-- (無限に投げてキューを埋められる)。
--
-- それが reporter_id の NOT NULL に落ちている。
CREATE TABLE reports (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    reporter_id  BIGINT      NOT NULL REFERENCES users(id),

    -- 通報できるのは投稿だけ。画像はコメント / スレッドに従属するので、
    -- 通報の単位にしない (画像だけを消す判断はモデレーター側が行う)。
    target_type  TEXT        NOT NULL,

    -- **こちらは BIGINT。** moderation_actions と違い、対象が
    -- threads / comments に限られるため型が混ざらない。
    -- 揃えて TEXT にはしない —— 混在していないものを文字列にすると、
    -- 一意制約と索引が無駄に大きくなる。
    --
    -- moderation_actions と同じく外部キーは張れない
    -- (target_type によって参照先テーブルが変わるため)。
    target_id    BIGINT      NOT NULL,

    reason       TEXT        NOT NULL,
    note         TEXT,

    status       TEXT        NOT NULL DEFAULT 'open',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at  TIMESTAMPTZ,
    resolved_by  BIGINT      REFERENCES users(id),

    CONSTRAINT reports_target_type_valid CHECK (target_type IN ('thread', 'comment')),
    CONSTRAINT reports_reason_valid CHECK (reason IN ('spam', 'abuse', 'illegal', 'other')),
    CONSTRAINT reports_status_valid CHECK (status IN ('open', 'resolved', 'rejected')),
    CONSTRAINT reports_note_length CHECK (note IS NULL OR char_length(note) <= 1000),

    -- **同じ人が同じ対象を 2 回通報できない。** 1 人で通報数を積み上げて
    -- キューの優先度を操作できないようにする。
    --
    -- UX に影響する: 2 回目は制約違反になるので、アプリ側で
    -- 「既に通報済みです」として正常に扱う必要がある
    -- (ADR 0011 の引き受けるコスト)。
    CONSTRAINT reports_unique_per_user UNIQUE (reporter_id, target_type, target_id),

    -- 解決済みなら解決者と時刻が揃っている。
    -- 片方だけ入った行は「誰が解決したか分からない解決済み通報」になり、
    -- moderation_actions と同じ理由で許容できない。
    CONSTRAINT reports_resolution_complete CHECK (
        (status = 'open'  AND resolved_at IS NULL AND resolved_by IS NULL)
        OR
        (status <> 'open' AND resolved_at IS NOT NULL AND resolved_by IS NOT NULL)
    )
);

-- 未処理の通報キュー。**部分索引にする。**
--
-- 通報は解決しても行が残る (誰が何を通報したかは記録として要る) ため、
-- テーブルは単調増加する。一方キューが読むのは status = 'open' だけで、
-- これは処理が追いついていれば常に小さい。
-- 全体に索引を張ると、増え続ける resolved / rejected まで載る。
--
-- created_at 順にするのは、古い通報から処理するため。
CREATE INDEX reports_open_idx ON reports (created_at) WHERE status = 'open';

-- 「この投稿は何件通報されているか」を引く。
-- 閾値で自動削除はしない (ADR 0011 決定 4) が、
-- キューの表示で件数を出すために要る。
CREATE INDEX reports_target_idx ON reports (target_type, target_id);

-- 外部キーには必ず索引を貼る (ADR 0016)。
-- reporter_id は一意制約 reports_unique_per_user の先頭列なのでそちらが兼ねる。
-- resolved_by は兼ねるものが無いため、ここで張る。
CREATE INDEX reports_resolved_by_idx ON reports (resolved_by) WHERE resolved_by IS NOT NULL;
