-- =============================================================================
-- 000012: 問い合わせ (contact_messages)
-- =============================================================================
-- 設計は docs/adr/0008-contact-and-mail.md、
-- 索引とマイグレーションの分割は docs/adr/0016-schema-and-indexes.md
-- (この番号は着手順 7 = Phase 8 に対応する)。
--
-- 【なぜ「メールを送る」機能なのにテーブルが要るのか】
-- **保存と送信を分ける** (ADR 0008 決定 1)。リクエストの中で同期に送ると、
-- メールプロバイダの障害がそのまま問い合わせの喪失になる ——
-- 利用者には 500 が返り、書いた内容は失われる。
-- このテーブルは outbox であり、**送信待ちの内容を落とさないための置き場**になる。
--
-- そのため列は「問い合わせの中身」と「送信の状態」の 2 つに割れている。
-- 前者は利用者が書いたもの、後者はワーカーが書き換えるものになる。
-- =============================================================================

CREATE TABLE contact_messages (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 【匿名でも問い合わせできる】
    -- **NULL を許す** (ADR 0008 決定 4)。「ログインできない」という
    -- 問い合わせが来る以上、ログインを必須にすると詰む。
    -- reports.reporter_id が NOT NULL なのと逆になるが、通報は他人への
    -- 申し立てなので責任の所在が要る、という違いによる。
    --
    -- 列名は user_id。「単に紐づくユーザー」であって、
    -- author_id (内容を書いた人) でも owner_id (資源の所有者) でもない
    -- (ADR 0016 の命名の統一)。
    --
    -- **ON DELETE を書かない。** ADR 0005 が「アカウント削除は行を消さず
    -- 匿名化する」と決めているため、この参照が宙に浮くことはない。
    user_id         BIGINT      REFERENCES users(id),

    -- 問い合わせの中身。**すべて利用者の入力**で、検証はしていない。
    -- email も「連絡先として書かれた文字列」以上のものではなく、
    -- ここへ自動返信は送らない (決定 2) し、メールヘッダにも入れない (決定 3)。
    name            TEXT        NOT NULL,
    email           TEXT        NOT NULL,
    subject         TEXT        NOT NULL,
    body            TEXT        NOT NULL,

    -- 【レート制限の集計に使う】
    -- アプリのメモリ上で数えると、**複数インスタンスでは効かない**
    -- (ECS のタスクが N 個あれば実質 N 倍まで通る)。
    -- 問い合わせは 1 日数十件を想定しており書き込み量が少ないので、
    -- 専用のカウンタストアを置かず**この列を数えるだけで足りる**
    -- (ADR 0008 決定 4「レート制限をどこで数えるか」)。
    --
    -- **INET 型にする。** TEXT だと "192.168.0.1" と "192.168.000.001" が
    -- 別の値になり、同じ送信元が別人として数えられる。
    --
    -- **NULL 可なのは、あとから消すため。** 個人データなので無期限には
    -- 保持せず、古い行から NULL にする (下の contact_ip_scrub 用の索引)。
    client_ip       INET,

    -- 送信の状態。ここから下はワーカーが書き換える列になる。
    status          TEXT        NOT NULL DEFAULT 'pending',

    -- 試行回数。**上限を超えたら failed にして打ち切る** (ADR 0008 決定 1)。
    -- 無限にリトライすると、送信できないメールが延々とプロバイダを叩き続ける。
    attempt_count   INT         NOT NULL DEFAULT 0,

    -- 直近の失敗理由。運用が「なぜ届いていないか」を知る唯一の手掛かりになる。
    last_error      TEXT,

    -- 次に試してよい時刻。リトライは指数バックオフで、ここに次回時刻を書く。
    -- Phase 2 の直列化失敗リトライと同じ考え方だが、
    -- **あちらはプロセス内、こちらは DB に状態を持つ**点が違う ——
    -- プロセスが落ちても待ち時間は失われない。
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at         TIMESTAMPTZ,

    CONSTRAINT contact_status_valid CHECK (status IN ('pending', 'sent', 'failed')),

    -- 最後の砦 (comments_body_length などと同じ位置づけ)。
    -- **アプリ側の定数 (internal/contact/domain/model) と OpenAPI の
    -- maxLength と、必ず同じ値にすること。** 3 か所が揃っていることは
    -- message_test.go が実際にファイルを読んで検査する。
    CONSTRAINT contact_name_length    CHECK (char_length(name)    BETWEEN 1 AND 100),
    CONSTRAINT contact_subject_length CHECK (char_length(subject) BETWEEN 1 AND 200),
    CONSTRAINT contact_body_length    CHECK (char_length(body)    BETWEEN 1 AND 5000),

    -- **ADR 0008 のスキーマには無い制約。**
    -- あちらは「本文・氏名・件名それぞれに上限」としか書いておらず、
    -- email が野放しだった。上限が無い列が 1 つでも残ると、
    -- そこが長さ制限の抜け道になる (5000 文字のアドレスを送れる)。
    -- 254 は RFC 5321 のアドレス長の上限。
    CONSTRAINT contact_email_length   CHECK (char_length(email)   BETWEEN 3 AND 254),

    -- 送信済みなら送信時刻が入っている。
    -- 片方だけの行は「いつ送ったか分からない送信済み」になり、
    -- 重複送信の調査ができなくなる (reports_resolution_complete と同じ理由)。
    CONSTRAINT contact_sent_complete CHECK (
        (status = 'sent' AND sent_at IS NOT NULL)
        OR
        (status <> 'sent' AND sent_at IS NULL)
    )
);

-- ワーカーが拾う行だけを索引に載せる (threads_alive_id_desc_idx と同じ考え方)。
--
-- **部分索引にする。** 送信済みの行は消さずに残る (問い合わせの記録として要る)
-- ため、テーブルは単調増加する。一方でワーカーが読むのは pending だけで、
-- これは送信が追いついていれば常に小さい。
--
-- 並びが (next_attempt_at, id) なのは、取り出しが
-- 「時刻が来ているものを、古い順に」だから。id を第 2 キーに置くのは、
-- next_attempt_at が一意でないため —— 同時刻の行が複数あると
-- 順序が不定になり、SKIP LOCKED の取りこぼしを再現しにくくする。
CREATE INDEX contact_pending_idx
    ON contact_messages (next_attempt_at, id)
    WHERE status = 'pending';

-- レート制限の集計用 (ADR 0008 決定 4)。
--
-- **client_ip が先頭。** 「この IP が直近 1 時間に何件送ったか」を引くので、
-- 等値で絞ってから時刻で範囲を切る形になる。
CREATE INDEX contact_rate_limit_idx ON contact_messages (client_ip, created_at);

-- 外部キーには必ず索引を貼る (ADR 0016 の区分 A)。
--
-- **ADR 0016 の索引表には載っていない。** あの表は ADR 0008 のスキーマから
-- 索引だけを転記しており、user_id が漏れていた。PostgreSQL は外部キーを
-- 張っても参照する側に索引を作らないため、users の行が更新されるたびに
-- contact_messages の全表走査が起きる。reports_resolved_by_idx を
-- 足したときと同じ理由になる。
--
-- **部分索引にする。** 匿名の問い合わせ (user_id IS NULL) が多数を占める
-- 想定で、NULL を載せても FK の整合確認には使われない。
CREATE INDEX contact_user_idx ON contact_messages (user_id) WHERE user_id IS NOT NULL;

-- client_ip を消し込む定期処理が拾う行 (ADR 0008「client_ip は個人データに
-- あたるため、無期限には保持しない」)。
--
-- **created_at だけの索引ではない。** 消し込みが読むのは
-- 「古くて、まだ client_ip が残っている行」であり、一度消したあとの行は
-- 二度と対象にならない。述語に含めておくと、消し込みが進むほど
-- 索引が小さくなる (images_reclaimable_idx と同じ形)。
CREATE INDEX contact_ip_scrub_idx
    ON contact_messages (created_at)
    WHERE client_ip IS NOT NULL;
