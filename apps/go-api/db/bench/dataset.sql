-- Phase 4 のベンチマーク用データセット。
--
-- **開発用シード (db/seed/seed.sql) とは別物。** あちらは目視で確認できる
-- 5 スレッドで、こちらは「索引が効くかどうかが結果に出る」規模を作る。
--
-- **本番では絶対に実行しないこと。** 先頭で TRUNCATE している。
--
-- 【規模の決め方】
-- db/query/threads.sql の実測 (2,005 スレッド / 200,016 コメント) と
-- 揃えてある。数字を比べられるようにするため ——
-- 規模が違うと「速くなった」のか「データが減った」のか分からない。
--
-- 【投稿者を混ぜる理由】
-- 一覧クエリは LEFT JOIN users で投稿者を解決する (ADR 0014)。
-- **前回の実測はこの JOIN が入る前のもので、以後測り直していない。**
-- 全員匿名のデータセットで測ると JOIN が空振りし、
-- 「投稿者の解決を含めたコスト」を測ったことにならない。
--
-- 【閲覧数を散らす理由】
-- 人気順の索引 (threads_alive_popular_idx) が効くかどうかは、
-- view_count の分布に依存する。全部 0 だと、同値の塊を id で辿るだけの
-- クエリになり、複合キーの意味が消える。

BEGIN;

TRUNCATE TABLE comments, threads, users RESTART IDENTITY CASCADE;

-- -----------------------------------------------------------------------------
-- 利用者 (投稿者の解決用)
-- -----------------------------------------------------------------------------
-- **スレッド数より少なくする。** 1 スレッド 1 利用者にすると、
-- JOIN が常に 1:1 になり、実際の分布 (少数の利用者が多く書く) とずれる。
INSERT INTO users (google_sub, email, display_name, public_id)
SELECT
    'bench-sub-' || n,
    'bench' || n || '@example.test',
    'ベンチ利用者 ' || n,
    -- **UUID v7 でなくてよい。** public_id の生成規則はアプリの関心で、
    -- ここで測りたいのは JOIN のコストになる。
    gen_random_uuid()
FROM generate_series(1, 200) AS n;

-- -----------------------------------------------------------------------------
-- スレッド 2,000 件
-- -----------------------------------------------------------------------------
-- タイトルは検索の分布を測れるように 3 種類の語を混ぜる。
--
--   ありふれた語 (「スレッド」)  : 全件に出る。GIN が候補を絞れない
--   中くらいの語 (「PostgreSQL」): 4 件に 1 件
--   珍しい語 (「ゼロ幅接合子」)   : 199 件に 1 件。GIN が最も効く
--
-- **199 は素数にしてある。** 最初は 200 件に 1 件にしていたが、
-- 下の論理削除が「100 件に 1 件」なので **200 の倍数はすべて
-- 100 の倍数でもあり、珍しい語のスレッドが 1 件残らず削除されていた。**
-- 一致 0 件のクエリを「珍しい語の実測」として記録しかけた
-- (ADR 0012 の Phase 4 節)。生成規則どうしが約数で噛み合う事故は、
-- **出力を数えるまで気づけない。**
--
-- ADR 0012 は「検索語が珍しいほど GIN が有利、ありふれた語ほど
-- id 順に読んで捨てるほうが有利」と書いた。それを実測する材料になる。
INSERT INTO threads (title, author_id, view_count, created_at)
SELECT
    'スレッド ' || n || ' '
        || CASE WHEN n % 4 = 0 THEN 'PostgreSQL の話 ' ELSE '' END
        || CASE WHEN n % 199 = 0 THEN 'ゼロ幅接合子 ' ELSE '' END
        || CASE WHEN n % 7 = 0 THEN '並行制御' ELSE '雑談' END,
    -- **5 件に 1 件は匿名にする** (author_id が NULL)。
    -- 全件に投稿者を付けると LEFT JOIN が INNER と同じ挙動になり、
    -- 「匿名が消えないこと」を測れない (ADR 0005 決定 2)。
    CASE WHEN n % 5 = 0 THEN NULL ELSE (n % 200) + 1 END,
    -- 閲覧数は歪んだ分布にする。**均等だと人気順の索引が
    -- 「ほぼ id 順」になり、複合キーを辿る意味が消える。**
    -- 少数のスレッドに極端に多い閲覧が集まる形が現実に近い。
    CASE
        WHEN n % 500 = 0 THEN 1000000 + n
        WHEN n % 50 = 0  THEN 10000 + n
        WHEN n % 5 = 0   THEN 100 + n
        ELSE n % 10
    END,
    now() - (n || ' minutes')::interval
FROM generate_series(1, 2000) AS n;

-- -----------------------------------------------------------------------------
-- コメント 200,000 件
-- -----------------------------------------------------------------------------
-- **スレッドごとに件数を散らす。** 均等に配ると、コメント数の集計が
-- どのスレッドでも同じコストになり、相関サブクエリの効きが見えない。
--
-- seq は (thread_id, seq) の UNIQUE を満たす必要がある
-- (マイグレーション 000004)。ここでは行番号をそのまま使う。
INSERT INTO comments (thread_id, seq, author_name, body, author_id, created_at)
SELECT
    t.id,
    row_number() OVER (PARTITION BY t.id ORDER BY c.n),
    'ベンチ',
    'コメント本文 ' || c.n || ' / スレッド ' || t.id,
    CASE WHEN c.n % 3 = 0 THEN NULL ELSE (c.n % 200) + 1 END,
    now() - (c.n || ' seconds')::interval
FROM threads t
-- スレッド ID に応じて 1〜200 件。合計はおよそ 20 万件になる。
CROSS JOIN LATERAL generate_series(1, (t.id % 200) + 1) AS c(n);

-- **10% を論理削除する。** 集計は削除済みを除外するので、
-- 除外が効いているかどうかで結果が変わる。
-- 全件生存のデータでは、部分索引の効果も測れない。
UPDATE comments SET deleted_at = now() WHERE id % 10 = 0;
UPDATE threads SET deleted_at = now() WHERE id % 100 = 0;

COMMIT;

-- -----------------------------------------------------------------------------
-- 統計と可視性マップを整える
-- -----------------------------------------------------------------------------
-- **VACUUM ANALYZE を必ず流す。** バルク INSERT の直後は
-- visibility map が未整備で Index Only Scan が Heap Fetches を伴う。
-- その状態で測ると、部分索引の効果 (db/query/threads.sql の実測) が
-- 一時的に消え、旧実装と同程度まで劣化した数字が出る。
--
-- **トランザクションの外で実行する** (VACUUM はトランザクション内で動かない)。
VACUUM (ANALYZE) threads;
VACUUM (ANALYZE) comments;
VACUUM (ANALYZE) users;
