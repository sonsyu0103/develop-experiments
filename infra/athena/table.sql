-- Athena のテーブル定義 (docs/adr/0010-log-pipeline.md 決定 2)。
--
-- **このファイルは本番用で、手元では実行しない。** ローカルの検証は
-- DuckDB が読む (infra/duckdb/)。両者の差はモジュール冒頭に書いてある。
--
-- <bucket> を実際のバケット名に置き換えて実行する。
--
-- =============================================================================
-- 罠 1: service をパーティション列にはできない
-- =============================================================================
-- S3 のキーは logs/service=go-api/dt=.../hour=.../ で、Hive 形式としては
-- service もパーティションに見える。しかし**レコードの中にも service がある**
-- (ADR 0010 の 4-2 の共通フィールド)。
--
-- Athena はパーティション列とデータ列の同名を許さないため、
-- 両方を宣言した DDL は作成時に落ちる。
--
-- ここでは **service を LOCATION に埋め込み、パーティションにしない**。
-- ADR 0010 決定 2 の storage.location.template がもともとその形になっている。
--
--   LOCATION 's3://<bucket>/logs/service=go-api/'
--
-- 【サービスが増えたとき】
-- service をパーティションにしたくなるが、そのときは
-- **レコード側のフィールド名を変える**しかない (例: service → svc)。
-- ログのフィールド名は実質的な契約なので (ADR 0010「引き受けるコスト」)、
-- 過去データと新データでクエリを分ける覚悟が要る。
-- 別テーブルを service ごとに作るほうが、たいてい安い。
--
-- =============================================================================
-- 罠 2: 宣言しなかった列は「無い」ことになる
-- =============================================================================
-- Athena はスキーマオンリード。**エラーにならず、静かに NULL になる。**
-- アプリが新しいフィールドを出し始めても、ここに足すまで見えない。
-- 4-6 の業務イベントを増やしたら、この DDL も一緒に更新する。
--
-- **手元の検査がこれを見る。** infra/duckdb/verify.py が
-- 「S3 に着地した列のうち、この DDL に無いもの」を検出して落とす。
-- 足し忘れたまま本番へ出す経路を塞いである。
--
-- =============================================================================
-- 罠 3: 同じ名前で型が違う列は宣言できない
-- =============================================================================
-- Athena で 1 つの列に 2 つの型は持てない。**アプリ側で名前を分けるしかない。**
--
-- 実際に 2 組ぶつかっていた (レビュー指摘):
--
--   status     http_request は int、画像と通報の「状態」は文字列
--              → image_status / report_status に分けた
--   target_id  通報の対象は bigint、モデレーション操作の対象は文字列
--              (スレッド ID と public_id が混在するため)
--              → モデレーション側を target_ref にした
--
-- **型が揺れても Athena はエラーを出さない。** SerDe が
-- ignore.malformed.json で読み飛ばすか、NULL になるだけになる。
-- .github/scripts/verify-log-events.py が**ソース側で**検出して CI で落とす ——
-- 着地したログを見るより、書いた時点で止めるほうが早い。
--
-- **この DDL と slog の型が一致することも、そちらが見る** (2026-08-24 に追加)。
-- それまで見ていたのは「アプリの中で型が揺れていないか」だけで、
-- 揺れずに**この表と食い違っている**場合は誰も気づけなかった。
-- 例: `limit` を bigint と宣言してあるのに slog.String で出す。
-- Athena では静かに NULL になり、クエリを書いた日に初めて分かる。

CREATE EXTERNAL TABLE IF NOT EXISTS go_api_logs (
    -- =========================================================================
    -- 共通フィールド (4-2)。service は上の罠 1 のため宣言しない。
    -- =========================================================================
    `time`       string,
    `level`      string,
    `msg`        string,
    `version`    string,
    `request_id` string,
    `user_id`    bigint,

    -- =========================================================================
    -- http_request
    -- =========================================================================
    `method`     string,
    `path`       string,
    -- **int。** 画像や通報の「状態」は image_status / report_status に分けてある
    -- (同名で型が違う列は宣言できない。下の「罠 3」)。
    `status`     int,
    -- **ナノ秒ではなく ms** (4-4)。単位を名前に含めてある。
    `latency_ms` double,

    -- =========================================================================
    -- コメント投稿と並行制御 (ADR 0019)
    -- =========================================================================
    `thread_id`  bigint,
    `comment_id` bigint,
    `seq`        int,
    -- 何回目の試行で成功したか。**本番で直列化失敗を数える起点はここ。**
    -- serialization_failure は DEBUG なので本番の S3 には 1 件も届かない。
    `attempts`   int,
    -- 各試行の番号 (DEBUG の serialization_failure)。開発でしか出ない。
    `attempt`    int,
    -- 直列化失敗 (40001) と採番の衝突 (23505) は同じイベント名で出るので、
    -- モードごとの競合の現れ方はこれで見分ける。
    `sqlstate`   string,
    -- ssi / pessimistic / unique / naive。Phase 4 でモード別に集計する。
    `mode`       string,
    -- 冪等キーで再生された応答か (ADR 0015)。
    `idempotent` boolean,

    -- =========================================================================
    -- 閲覧数 (ADR 0006)
    -- =========================================================================
    `threads`    bigint,
    `increments` bigint,
    -- フラッシュで実際に更新された行数。バッファの件数と食い違ったら、
    -- 閲覧後に削除されたスレッドがあったことを意味する。
    `affected`   bigint,

    -- =========================================================================
    -- 定期処理 (scheduler)
    -- =========================================================================
    `job`          string,
    `elapsed_ms`   bigint,
    `rounds`       int,
    -- **Duration を出さない。** JSON ハンドラではナノ秒の整数になり、
    -- Athena で毎回 / 1e6 を書くことになる (4-4)。
    `interval_ms`  bigint,

    -- =========================================================================
    -- 画像 (ADR 0007)
    -- =========================================================================
    `image_id`     string,
    `object_key`   string,
    `image_status` string,
    `deleted`      int,
    `marked`       int,
    `failed`       int,

    -- =========================================================================
    -- モデレーション (ADR 0011)
    -- =========================================================================
    `action`               string,
    `actor_id`             bigint,
    `moderation_action_id` bigint,
    `report_id`            bigint,
    `report_status`        string,
    `target_type`          string,
    -- **通報の対象 ID は bigint、モデレーション操作の対象は文字列**
    -- (スレッド ID と利用者の public_id が混在するため)。
    -- 同名にできないので列を分けてある (下の「罠 3」)。
    `target_id`            bigint,
    `target_ref`           string,
    `role`                 string,
    `new_role`             string,
    `owner_id`             bigint,

    -- =========================================================================
    -- 問い合わせとメール送信 (ADR 0008)
    -- =========================================================================
    -- **この節は丸ごと抜けていた。** Phase 8 で contact_* のイベントを
    -- 出し始めたときに、この DDL を更新していなかった ——
    -- 上の「罠 2」がまさに起きていて、`contact_id` は
    -- **エラーにならず静かに NULL** になっていた。
    -- 控えの失敗 (contact_auto_reply_failed) を数えようとして気づいた。
    `contact_id`  bigint,
    -- レート制限 (決定 4)。**client_ip は個人データ**なので、
    -- ログの保持期間 (決定 6 の 400 日) が DB 側の消し込みと揃っている
    -- ことが前提になる。
    `client_ip`   string,
    `count`       bigint,
    -- **limit だけが予約語。** DDL のバッククォートでは通るが、
    -- クエリ側では二重引用符で囲まないと構文エラーになる ("limit")。
    -- count は Trino / Athena engine v3 の予約語ではない (レビュー指摘)。
    -- 罠 3 のように「宣言できない」わけではないので改名はしていない。
    `limit`       bigint,
    -- 送信ワーカーが 1 周回で確保した件数と、実際に扱った件数。
    -- **食い違いはリース予算で打ち切ったことを意味する** ——
    -- 常に食い違うなら、バッチが送信の速さに追いついていない。
    `claimed`     int,
    `handled`     int,
    -- **未送信の最古の行の滞留時間** (contact_pending_age)。
    -- 送信ワーカーが詰まっていることを示す本命の信号で、
    -- 「一定時間このイベントが出ていないこと」も監視の対象になる
    -- (ADR 0008「実装して分かったこと 9」)。
    -- **この節を足した時点でこれも漏らしていた** (レビュー指摘) ——
    -- 手作業の洗い出しは取りこぼす、を地で行った形になる。
    -- 以後は verify-log-events.py が DDL との差分を CI で見る。
    `oldest_age_ms` bigint,

    -- =========================================================================
    -- 起動時と防御層
    -- =========================================================================
    `addr`            string,
    `bucket`          string,
    `endpoint`        string,
    `bootstrap_admin` boolean,
    -- メール送信の結線 (contact_mail_enabled)。**起動時に 1 回だけ出る。**
    -- 「控えが 1 通も出ていない」ときに、設定が入っているかを
    -- 先に切り分けられる (ADR 0008 決定 2)。
    `smtp_host`       string,
    `starttls`        boolean,
    -- csrf_rejected が「なぜ弾いたか」(ADR 0013)。
    -- **value に入るのは Origin ヘッダの値**で、利用者の入力ではない。
    `reason`          string,
    `value`           string,
    `component`       string,
    `configured_len`  int,
    `received_len`    int,

    -- =========================================================================
    -- 障害時にいちばん要るもの
    -- =========================================================================
    `error`      string,
    -- **panic は string に固定してある。** recover した値は任意の型で、
    -- slog.Any のままだと JSON に出る形が呼び出しごとに変わる。
    `panic`      string,
    `stack`      string,
    -- 制約違反の詳細 (postgres/errors.go)。
    `op`         string,
    `constraint` string,

    -- =========================================================================
    -- FireLens が付けるコンテナのメタデータ
    -- =========================================================================
    -- Reserve_Data On で残している (これを落とすと、
    -- どのタスクが出したログか分からなくなる)。
    `container_id`   string,
    `container_name` string,
    `ecs_task_arn`   string,
    `source`         string,

    -- **JSON でない行はここに残る。** go run のコンパイルエラーや
    -- panic のスタックトレースはパースできず、log キーのまま素通しする。
    -- 障害時に最も見たい行なので、捨てずに拾えるようにしておく。
    `log`        string
)
PARTITIONED BY (
    `dt`   string,
    `hour` string
)
ROW FORMAT SERDE 'org.openx.data.jsonserde.JsonSerDe'
WITH SERDEPROPERTIES (
    -- パースできないレコードで**クエリ全体を落とさない**。
    -- ログ基盤は「壊れた 1 行のせいで何も読めない」が最も困る。
    'ignore.malformed.json' = 'true',
    'dots.in.keys'          = 'true'
)
LOCATION 's3://<bucket>/logs/service=go-api/'
TBLPROPERTIES (
    -- partition projection (決定 2)。
    --
    -- **これを外すと Athena は破産する。** パーティションが無いクエリは
    -- 毎回全期間を読む。加えて projection なら MSCK REPAIR TABLE も
    -- Glue Crawler も要らず、「昨日のログだけ検索できない」という
    -- Crawler 失敗の事故モードが丸ごと消える。
    'projection.enabled'        = 'true',
    'projection.dt.type'        = 'date',
    'projection.dt.format'      = 'yyyy-MM-dd',
    -- 開始日は運用開始日に合わせる。NOW は毎日自動で伸びる。
    'projection.dt.range'       = '2026-08-01,NOW',
    'projection.hour.type'      = 'integer',
    'projection.hour.range'     = '0,23',
    -- **2 桁に固定する。** s3_key_format の %H が 08 のような形なので、
    -- digits を指定しないと 8 で探しに行って 0 件になる。
    'projection.hour.digits'    = '2',
    'storage.location.template' = 's3://<bucket>/logs/service=go-api/dt=${dt}/hour=${hour}/'
);
